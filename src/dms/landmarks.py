# ============================================================
# IMPORTS
# ============================================================

import time
from pathlib import Path

import cv2
import mediapipe as mp
import numpy as np


# ============================================================
# MODEL CONFIGURATION
# ============================================================

# Project directory:
# orbbec-astra-scanner/
PROJECT_DIR = Path(__file__).resolve().parent.parent.parent

# Expected model location:
# orbbec-astra-scanner/models/pose_landmarker_lite.task
MODEL_PATH = (
    PROJECT_DIR
    / "models"
    / "pose_landmarker_lite.task"
)

NUM_POSES = 1

MIN_POSE_DETECTION_CONFIDENCE = 0.5
MIN_POSE_PRESENCE_CONFIDENCE = 0.5
MIN_TRACKING_CONFIDENCE = 0.5

MIN_LANDMARK_VISIBILITY = 0.55


# ============================================================
# SKELETON CONFIGURATION
# ============================================================

# MediaPipe Pose Landmarker landmark connections.
# Preserved from the original viewer_unified.py.

POSE_CONNECTIONS = [
    (11, 12),
    (11, 13),
    (13, 15),
    (12, 14),
    (14, 16),

    (11, 23),
    (12, 24),
    (23, 24),

    (23, 25),
    (25, 27),
    (24, 26),
    (26, 28),

    (27, 29),
    (29, 31),
    (28, 30),
    (30, 32),

    (15, 17),
    (15, 19),
    (15, 21),

    (16, 18),
    (16, 20),
    (16, 22),

    (0, 2),
    (2, 5),
    (5, 0),

    (0, 1),
    (1, 4),
    (4, 0),

    (7, 8),
]


# OpenCV uses BGR colors.
SKELETON_LINE_COLOR = (0, 255, 0)
LANDMARK_CENTER_COLOR = (0, 0, 255)
LANDMARK_OUTLINE_COLOR = (255, 255, 255)


# ============================================================
# LANDMARK VALIDATION
# ============================================================

def landmark_ok(point, minimum=MIN_LANDMARK_VISIBILITY):
    """
    Check whether a detected landmark is sufficiently reliable.

    Args:
        point:
            MediaPipe landmark object.

        minimum:
            Minimum visibility and presence threshold.

    Returns:
        bool:
            True if the landmark satisfies the checks.
            False otherwise.
    """

    if point is None:
        return False

    return (
        getattr(point, "visibility", 1.0) >= minimum
        and getattr(point, "presence", 1.0) >= minimum
        and np.isfinite(point.x)
        and np.isfinite(point.y)
    )


# ============================================================
# SKELETON VISUALIZATION
# ============================================================

def draw_skeleton(image, landmarks):
    """
    Draw detected body landmarks and skeleton connections.

    Args:
        image:
            OpenCV BGR image.

        landmarks:
            List of MediaPipe pose landmarks.

    Returns:
        image:
            Original image with skeleton overlay applied.

    Notes:
        - The supplied image is modified in place.
        - Invalid or low-visibility landmarks are skipped.
        - This function performs visualization only.
    """

    if image is None or landmarks is None:
        return image

    height, width = image.shape[:2]

    def get_point(index):
        """
        Convert a normalized landmark into image coordinates.
        """

        if index >= len(landmarks):
            return None

        point = landmarks[index]

        if not landmark_ok(point, 0.5):
            return None

        x = int(point.x * width)
        y = int(point.y * height)

        if 0 <= x < width and 0 <= y < height:
            return x, y

        return None

    # Draw skeleton connections.
    for start, end in POSE_CONNECTIONS:

        point_a = get_point(start)
        point_b = get_point(end)

        if point_a is None or point_b is None:
            continue

        cv2.line(
            image,
            point_a,
            point_b,
            SKELETON_LINE_COLOR,
            2,
            cv2.LINE_AA
        )

    # Draw individual landmarks.
    for index in range(len(landmarks)):

        point = get_point(index)

        if point is None:
            continue

        cv2.circle(
            image,
            point,
            4,
            LANDMARK_CENTER_COLOR,
            -1,
            cv2.LINE_AA
        )

        cv2.circle(
            image,
            point,
            5,
            LANDMARK_OUTLINE_COLOR,
            1,
            cv2.LINE_AA
        )

    return image


# ============================================================
# MEDIAPIPE LANDMARK DETECTOR
# ============================================================

class LandmarkDetector:
    """
    Manages MediaPipe pose estimation across video frames.

    The model is initialized once and reused throughout
    the application lifecycle.

    The main application is responsible for acquiring frames
    and supplying them to this detector.
    """

    def __init__(self, model_path=MODEL_PATH):

        self.model_path = Path(model_path)

        self.pose = None

        self.last_inference_ms = 0.0

        self.pose_detected = False

        self.previous_timestamp_ms = -1

        self.start_time = time.monotonic()

    # --------------------------------------------------------
    # INITIALIZATION
    # --------------------------------------------------------

    def initialize(self):
        """
        Initialize the MediaPipe Pose Landmarker model.
        """

        if self.pose is not None:
            return

        if not self.model_path.is_file():
            raise FileNotFoundError(
                f"MediaPipe model not found: {self.model_path}"
            )

        options = mp.tasks.vision.PoseLandmarkerOptions(

            base_options=mp.tasks.BaseOptions(
                model_asset_path=str(self.model_path)
            ),

            running_mode=mp.tasks.vision.RunningMode.VIDEO,

            num_poses=NUM_POSES,

            min_pose_detection_confidence=(
                MIN_POSE_DETECTION_CONFIDENCE
            ),

            min_pose_presence_confidence=(
                MIN_POSE_PRESENCE_CONFIDENCE
            ),

            min_tracking_confidence=(
                MIN_TRACKING_CONFIDENCE
            )
        )

        self.pose = (
            mp.tasks.vision.PoseLandmarker
            .create_from_options(options)
        )

        self.start_time = time.monotonic()
        self.previous_timestamp_ms = -1

        print("[Landmarks] MediaPipe model initialized.")

    # --------------------------------------------------------
    # FRAME PROCESSING
    # --------------------------------------------------------

    def detect(self, bgr_frame, timestamp_ms=None):
        """
        Detect human pose landmarks in an RGB camera frame.

        Args:
            bgr_frame:
                OpenCV BGR image.

            timestamp_ms:
                Optional frame timestamp in milliseconds.
                Must increase between consecutive frames.

        Returns:
            landmarks:
                List containing 33 MediaPipe landmarks,
                or None if no pose is detected.

            inference_ms:
                Model inference latency in milliseconds.
        """

        if self.pose is None:
            raise RuntimeError(
                "LandmarkDetector must be initialized "
                "before calling detect()."
            )

        if bgr_frame is None:
            self.pose_detected = False
            self.last_inference_ms = 0.0

            return None, 0.0

        # Convert OpenCV BGR to RGB.
        rgb_frame = cv2.cvtColor(
            bgr_frame,
            cv2.COLOR_BGR2RGB
        )

        # Create MediaPipe image.
        mp_image = mp.Image(
            image_format=mp.ImageFormat.SRGB,
            data=np.ascontiguousarray(rgb_frame)
        )

        # Generate timestamp if one was not supplied.
        if timestamp_ms is None:

            timestamp_ms = int(
                (time.monotonic() - self.start_time) * 1000
            )

        # MediaPipe VIDEO mode requires increasing timestamps.
        timestamp_ms = max(
            int(timestamp_ms),
            self.previous_timestamp_ms + 1
        )

        self.previous_timestamp_ms = timestamp_ms

        # Measure MediaPipe inference latency.
        inference_start = time.perf_counter()

        result = self.pose.detect_for_video(
            mp_image,
            timestamp_ms
        )

        self.last_inference_ms = (
            time.perf_counter() - inference_start
        ) * 1000.0

        # Check for detected poses.
        if not result.pose_landmarks:

            self.pose_detected = False

            return None, self.last_inference_ms

        # One driver is supported by the current prototype.
        landmarks = result.pose_landmarks[0]

        self.pose_detected = True

        return landmarks, self.last_inference_ms

    # --------------------------------------------------------
    # VISUALIZATION
    # --------------------------------------------------------

    def draw(self, image, landmarks):
        """
        Draw the detected pose skeleton on an image.
        """

        return draw_skeleton(image, landmarks)

    # --------------------------------------------------------
    # SHUTDOWN
    # --------------------------------------------------------

    def close(self):
        """
        Release MediaPipe model resources.
        """

        if self.pose is not None:

            self.pose.close()
            self.pose = None

            print("[Landmarks] MediaPipe model released.")

        self.pose_detected = False

    # --------------------------------------------------------
    # CONTEXT MANAGER SUPPORT
    # --------------------------------------------------------

    def __enter__(self):
        self.initialize()
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        self.close()
